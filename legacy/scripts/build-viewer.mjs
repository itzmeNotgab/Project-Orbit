// Regenerates src/viewer/viewerHtml.ts from viewer-src/viewer.js.
// Run after editing the viewer:  node scripts/build-viewer.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const js = readFileSync(new URL('../viewer-src/viewer.js', import.meta.url), 'utf8');
const html =
  '<!doctype html><html><head><meta charset="utf-8">' +
  '<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">' +
  '<style>html,body{margin:0;height:100%;background:transparent;overflow:hidden;touch-action:none}canvas{display:block;width:100%;height:100%;touch-action:none}</style>' +
  '</head><body><canvas id="c"></canvas><script>' +
  js.replace(/<\/script>/gi, '<\\/script>') +
  '</script></body></html>';
const out =
  '// GENERATED by scripts/build-viewer.mjs from viewer-src/viewer.js. Do not edit by hand.\n' +
  'export const VIEWER_HTML = ' +
  JSON.stringify(html) +
  ';\n';
writeFileSync(new URL('../src/viewer/viewerHtml.ts', import.meta.url), out);
console.log('wrote src/viewer/viewerHtml.ts (' + out.length + ' bytes)');
